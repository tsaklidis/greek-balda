#!/usr/bin/env python3
"""Build the game's word lists.

js/dictionary.js  (all words) from data/dic_gr_lowercase.js:
  every spell-checker word form except proper nouns.

js/nouns.js  (nouns only, the default) from the Greek Wiktionary noun export:
  only noun lemmas, i.e. headwords in the nominative (usually singular).
  Inflected forms, proper nouns, polytonic spellings and words whose every
  meaning is archaic / katharevousa / dialectal are dropped. Nouns that are not
  also in data/dic_gr_lowercase.js are marked "rare": the player may play them,
  but the computer and the hints never use them.

  The repository keeps a compact copy of that export in data/el_wiktionary_nouns.jsonl.gz
  (every noun entry with its tags, definitions and inflection links; 185 MB -> ~4 MB).
  The original export (deprecated by kaikki.org, may disappear) was downloaded from
  https://kaikki.org/elwiktionary/Greek/pos-noun/kaikki.org-dictionary-Greek-by-pos-noun.jsonl
  Data extracted from Wiktionary (https://el.wiktionary.org), CC BY-SA 4.0.

All words are stripped of accents, upper-cased (final sigma -> Σ), sorted,
front-coded and written with the 24 Greek capitals mapped to a-x.

Usage:
  python3 tools/build_dictionary.py                     # both files, nouns from data/
  python3 tools/build_dictionary.py path/to/nouns.jsonl  # both files, nouns from another
                                                        # export (.jsonl or .jsonl.gz)
"""
import gzip
import json
import os
import re
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPELL_SRC = os.path.join(ROOT, "data", "dic_gr_lowercase.js")
ALL_OUT = os.path.join(ROOT, "js", "dictionary.js")
NOUNS_OUT = os.path.join(ROOT, "js", "nouns.js")
NOUNS_SRC = os.path.join(ROOT, "data", "el_wiktionary_nouns.jsonl.gz")

ALPHABET = "ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩ"
CODES = "abcdefghijklmnopqrstuvwx"
MIN_LEN = 3
MAX_LEN = 25  # the board has 25 cells
MAX_PREFIX = 40  # prefix length is stored as chr(48 + n), must stay below 'a'
RARE_MARK = "~"  # written after a word that only the player may use

# A noun is skipped when every one of its meanings carries one of these tags.
ODD_SENSE_TAGS = {
    "archaic", "obsolete", "dated", "historical", "Katharevousa", "Ancient-Greek",
    "dialectal", "Cretan", "Cypriot", "Pontic", "Heptanese", "Maniot",
}


def normalize(word):
    word = unicodedata.normalize("NFD", word)
    word = "".join(c for c in word if not unicodedata.combining(c))
    return word.upper().replace("ς", "Σ")


def playable(word):
    return MIN_LEN <= len(word) <= MAX_LEN and all(c in ALPHABET for c in word)


def encode(words, rare=frozenset()):
    """Front-code a set of normalized words; rare words get RARE_MARK appended."""
    table = str.maketrans(ALPHABET, CODES)
    out, prev = [], ""
    for w in sorted(words):
        p = 0
        limit = min(len(w), len(prev), MAX_PREFIX)
        while p < limit and w[p] == prev[p]:
            p += 1
        out.append(chr(48 + p) + w[p:].translate(table) + (RARE_MARK if w in rare else ""))
        prev = w
    return "".join(out)


def write_js(path, variable, data, source):
    with open(path, "w", encoding="ascii") as f:
        f.write(f"// Generated by tools/build_dictionary.py from {source}. Do not edit.\n")
        f.write("// Front-coded: each entry is chr(48 + shared prefix length) + suffix, letters a-x map\n")
        f.write(f"// to the 24 Greek capitals in order; '{RARE_MARK}' marks a word the computer never plays.\n")
        f.write(f'window.{variable} = "{data}";\n')


def spell_words():
    with open(SPELL_SRC, encoding="utf-8") as f:
        raw = re.findall(r"'([^']*)'", f.read())
    words = {normalize(w) for w in raw if w and not w[0].isupper()}
    return {w for w in words if playable(w)}


def is_polytonic(word):
    return any("ἀ" <= c <= "῿" for c in word)


def noun_lemmas(jsonl_path):
    nouns = set()
    opener = gzip.open if jsonl_path.endswith(".gz") else open
    with opener(jsonl_path, "rt", encoding="utf-8") as f:
        for line in f:
            entry = json.loads(line)
            if entry.get("lang_code") != "el" or entry.get("pos") != "noun":
                continue
            # The "form-of" tag marks inflected forms (e.g. ήλιο -> ήλιος). The entry-level
            # "form_of" field is not a filter: here it lists alternative spellings of lemmas.
            tags = entry.get("tags", [])
            if "form-of" in tags or "proper-noun" in tags:
                continue
            word = entry["word"]
            if not word or word[0].isupper() or is_polytonic(word):
                continue
            senses = entry.get("senses", [])
            if senses and all("form_of" in s or "alt_of" in s for s in senses):
                continue
            if senses and all(set(s.get("tags", [])) & ODD_SENSE_TAGS for s in senses):
                continue
            n = normalize(word)
            if playable(n):
                nouns.add(n)
    return nouns


def main():
    spell = spell_words()
    write_js(ALL_OUT, "BALDA_DICTIONARY", encode(spell), "data/dic_gr_lowercase.js")
    print(f"{ALL_OUT}: {len(spell)} words, {os.path.getsize(ALL_OUT)} bytes")

    nouns_src = sys.argv[1] if len(sys.argv) > 1 else NOUNS_SRC
    if os.path.exists(nouns_src):
        nouns = noun_lemmas(nouns_src)
        rare = frozenset(nouns - spell)
        write_js(NOUNS_OUT, "BALDA_NOUNS", encode(nouns, rare), "the Greek Wiktionary noun export (CC BY-SA 4.0)")
        print(f"{NOUNS_OUT}: {len(nouns)} nouns ({len(nouns) - len(rare)} common, {len(rare)} rare), "
              f"{os.path.getsize(NOUNS_OUT)} bytes")


if __name__ == "__main__":
    main()
